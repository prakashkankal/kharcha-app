export const normalizeIconName = (value) => {
  const normalizedValue = String(value || 'package').replace(/\uFE0F/g, '');
  return EMOJI_ICON_NAMES[normalizedValue] || normalizedValue;
};

export const getLucideIcon = (name) => ICONS[normalizeIconName(name)] || Package;
